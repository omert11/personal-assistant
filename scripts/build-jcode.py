#!/usr/bin/env python3
"""Install the jcode port of this Claude Code plugin into ~/.jcode/ (or $JCODE_HOME).

jcode has no plugin format, so this writes straight into its home directory and
touches only what it owns:
  rules/*.md + jcode/rules.md -> prompt-overlay.md (global prompt layer)
  skills/, local-skills/      -> skills/<name>/ (manifest-tracked, pruned)
  whatsapp MCP (if installed) -> mcp.json `whatsapp` entry
  jcode/build.json + core.md  -> config.toml keys (provider, model, hooks, auth trust)
  telemetry                   -> no_telemetry marker
Claude-side sources stay canonical; jcode/ holds only jcode-specific bits.
Markdown from rules/ and skills is passed through jcode/translate.sed.
Idempotent: unchanged files are not rewritten. jcode's session_start hook re-runs
it, so edits apply from the next session.

Usage: python3 scripts/build-jcode.py [--quiet]
"""

from __future__ import annotations

import argparse
import fcntl
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "jcode"
JHOME = Path(os.environ.get("JCODE_HOME") or Path.home() / ".jcode")
MANIFEST = ".personal-assistant-manifest"
SED_FILE = SRC / "translate.sed"
HEAVY_HOOK = str(SRC / "hooks" / "heavy-transform")
REFRESH_HOOK = f"python3 {Path(__file__).resolve()} --quiet"
CREDENTIALS_TRUST = "claude_code_credentials|{}"
OVERLAY_HEADER = "<!-- Generated by personal-assistant scripts/build-jcode.py from rules/; edits are overwritten. -->\n\n"
ORCHESTRATOR_RE = re.compile(r"^\|\s*Orchestrator\s*\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|", re.M)
REEXEC_ENV = "PA_BUILD_JCODE_REEXEC"


def load_omp_module():
    """Reuse build-omp.py's skill frontmatter transform and MCP discovery."""
    spec = importlib.util.spec_from_file_location("build_omp", ROOT / "scripts" / "build-omp.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


omp = load_omp_module()
BuildError = omp.BuildError


def ensure_tomlkit():
    """tomlkit keeps the rest of jcode's config.toml intact; fetch it through uv when missing."""
    try:
        import tomlkit  # noqa: F401
    except ImportError:
        if os.environ.get(REEXEC_ENV):
            raise BuildError("tomlkit unavailable even under uv")
        uv = shutil.which("uv") or str(Path.home() / ".local" / "bin" / "uv")
        if not os.access(uv, os.X_OK):
            raise BuildError("tomlkit missing and uv not found")
        os.environ[REEXEC_ENV] = "1"
        os.execv(uv, [uv, "run", "--quiet", "--no-project", "--with", "tomlkit", "python3", *sys.argv])


class Installer:
    def __init__(self, quiet: bool) -> None:
        self.quiet = quiet
        self.builder = omp.Builder(quiet)
        self.changed: list[str] = []

    def info(self, msg: str) -> None:
        if not self.quiet:
            print(msg)

    def put(self, path: Path, data: bytes, mode: int | None = None) -> None:
        """Write only when content differs (atomic replace)."""
        if path.is_file() and path.read_bytes() == data:
            if mode is not None and path.stat().st_mode & 0o777 != mode:
                os.chmod(path, mode)
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.pa-tmp")
        tmp.write_bytes(data)
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
        self.changed.append(str(path.relative_to(JHOME)))

    @staticmethod
    def translate(texts: list[str]) -> list[str]:
        """Run jcode/translate.sed over all texts in one sed call (rules are line-local)."""
        if not texts:
            return []
        split = f"{omp.SED_SPLIT}\n"
        if any(omp.SED_SPLIT in t for t in texts):
            raise BuildError("sed split marker found in source text")
        joined = split.join(t if t.endswith("\n") else t + "\n" for t in texts)
        proc = subprocess.run(
            ["sed", "-E", "-f", str(SED_FILE)],
            input=joined.encode("utf-8"),
            capture_output=True,
            env=dict(os.environ, LC_ALL="C"),
        )
        if proc.returncode != 0:
            raise BuildError(f"sed failed: {proc.stderr.decode('utf-8', 'replace').strip()}")
        out = proc.stdout.decode("utf-8").split(split)
        if len(out) != len(texts):
            raise BuildError("sed output split mismatch")
        return [o if t.endswith("\n") else o[:-1] for t, o in zip(texts, out)]

    # --- skills ------------------------------------------------------------
    def skill_files(self, name: str, base: Path) -> dict[Path, tuple[bytes, int]]:
        skill_dir = str(JHOME / "skills" / name)
        files: dict[Path, tuple[bytes, int]] = {}
        texts: dict[Path, str] = {}
        for f in self.builder.iter_files(base):
            rel = f.relative_to(base)
            data = f.read_bytes()
            mode = f.stat().st_mode & 0o777
            if f.suffix in omp.TEXT_SUFFIXES:
                try:
                    text = data.decode("utf-8")
                except UnicodeDecodeError:
                    pass
                else:
                    text = text.replace("${CLAUDE_PLUGIN_ROOT}", str(ROOT))
                    texts[rel] = omp.SKILL_DIR_RE.sub(lambda _m: skill_dir, text)
            files[rel] = (data, mode)
        md = [rel for rel in texts if rel.suffix == ".md"]
        for rel, text in zip(md, self.translate([texts[rel] for rel in md])):
            texts[rel] = text
        for rel, text in texts.items():
            if rel == Path("SKILL.md"):
                text = self.builder.transform_skill_md(text, Path(name) / rel)
            files[rel] = (text.encode("utf-8"), files[rel][1])
        return files

    def install_skills(self, exclude: set[str]) -> None:
        bases: dict[str, Path] = {}
        for src_root in (ROOT / "skills", ROOT / "local-skills"):
            if not src_root.is_dir():
                continue
            for p in sorted(src_root.iterdir()):
                if not (p / "SKILL.md").is_file() or p.name in exclude:
                    continue
                if p.name in bases:
                    raise BuildError(f"skill name collision: {p.relative_to(ROOT)} vs {bases[p.name].relative_to(ROOT)}")
                bases[p.name] = p

        dst_root = JHOME / "skills"
        dst_root.mkdir(parents=True, exist_ok=True)
        manifest = dst_root / MANIFEST
        managed = set(manifest.read_text().split()) if manifest.is_file() else set()

        for name, base in bases.items():
            dst = dst_root / name
            files = self.skill_files(name, base)
            for rel, (data, mode) in files.items():
                self.put(dst / rel, data, mode)
            # Drop files that no longer exist in the source.
            for existing in sorted(dst.rglob("*"), reverse=True):
                rel = existing.relative_to(dst)
                if existing.is_file() and rel not in files:
                    existing.unlink()
                    self.changed.append(str(existing.relative_to(JHOME)))
                elif existing.is_dir() and not any(existing.iterdir()):
                    existing.rmdir()

        for name in sorted(managed - set(bases)):
            shutil.rmtree(dst_root / name, ignore_errors=True)
            self.changed.append(f"skills/{name} (removed)")
        self.put(manifest, ("\n".join(sorted(bases)) + "\n").encode())

    # --- rules -------------------------------------------------------------
    def install_overlay(self) -> None:
        parts = []
        for f in sorted((ROOT / "rules").glob("*.md")):
            text = f.read_text(encoding="utf-8")
            fm, body = self.builder.split_frontmatter(text)
            parts.append(body if fm is not None else text)
        parts = [p.strip("\n") for p in self.translate(parts)]
        parts.append((SRC / "rules.md").read_text(encoding="utf-8").strip("\n"))
        self.put(JHOME / "prompt-overlay.md", (OVERLAY_HEADER + "\n\n".join(parts) + "\n").encode())

    # --- MCP ---------------------------------------------------------------
    def install_mcp(self) -> None:
        if not omp.WHATSAPP_SERVER.is_dir():
            return
        uv = shutil.which("uv") or str(Path.home() / ".local" / "bin" / "uv")
        path = JHOME / "mcp.json"
        data = json.loads(path.read_text()) if path.is_file() else {}
        data.setdefault("mcpServers", {})["whatsapp"] = {
            "command": uv,
            "args": ["--directory", str(omp.WHATSAPP_SERVER), "run", "main.py"],
            "env": {},
        }
        self.put(path, (json.dumps(data, indent=2) + "\n").encode())

    # --- config.toml -------------------------------------------------------
    @staticmethod
    def orchestrator() -> tuple[str, str]:
        """Default model/effort from the Orchestrator row of the core.md sub-agent table."""
        m = ORCHESTRATOR_RE.search((ROOT / "rules" / "core.md").read_text(encoding="utf-8"))
        if m is None:
            raise BuildError("rules/core.md: Orchestrator row missing from the sub-agent table")
        parts = m.group(1).split()
        if len(parts) != 2:
            raise BuildError(f"rules/core.md: Orchestrator model must be `<family> <version>`, got `{m.group(1)}`")
        family, version = parts
        return f"claude-{family}-{version.replace('.', '-')}", m.group(2)

    @staticmethod
    def hook_list(table, key: str) -> list[str]:
        value = table.get(key)
        if value is None or value == "":
            return []
        return [str(v) for v in value] if isinstance(value, list) else [str(value)]

    def install_config(self, cfg: dict) -> None:
        import tomlkit

        path = JHOME / "config.toml"
        doc = tomlkit.parse(path.read_text(encoding="utf-8")) if path.is_file() else tomlkit.document()

        def table(name: str):
            if name not in doc:
                doc[name] = tomlkit.table()
            return doc[name]

        for section, values in cfg.items():
            t = table(section)
            for key, value in values.items():
                t[key] = value

        model, effort = self.orchestrator()
        provider = table("provider")
        provider["default_model"] = model
        provider["anthropic_reasoning_effort"] = effort

        hooks = table("hooks")
        for key, cmd in (("pre_tool_transform", HEAVY_HOOK), ("session_start", REFRESH_HOOK)):
            cmds = self.hook_list(hooks, key)
            if cmd not in cmds:
                hooks[key] = cmds + [cmd]

        # Read ~/.claude/.credentials.json in place: the Claude hub keeps it fresh (access token only).
        auth = table("auth")
        creds = (Path.home() / ".claude" / ".credentials.json").resolve()
        entry = CREDENTIALS_TRUST.format(str(creds).lower())
        trusted = [str(v) for v in auth.get("trusted_external_source_paths", [])]
        if not any(v.strip().lower() == entry for v in trusted):
            auth["trusted_external_source_paths"] = sorted(trusted + [entry])

        self.put(path, tomlkit.dumps(doc).encode("utf-8"))

    # --- telemetry ---------------------------------------------------------
    def install_telemetry(self) -> None:
        marker = JHOME / "no_telemetry"
        if not marker.exists():
            self.put(marker, b"")

    def run(self) -> None:
        cfg = self.builder.load_json(SRC / "build.json", {})
        if not isinstance(cfg, dict):
            raise BuildError("jcode/build.json must be an object")
        self.install_skills(set(cfg.get("excludeSkills", [])))
        self.install_overlay()
        self.install_mcp()
        self.install_config(cfg.get("config", {}))
        self.install_telemetry()


def main() -> int:
    ap = argparse.ArgumentParser(description="Install the jcode port into ~/.jcode/.")
    ap.add_argument("--quiet", action="store_true", help="print only warnings and errors")
    args = ap.parse_args()

    try:
        ensure_tomlkit()
        JHOME.mkdir(parents=True, exist_ok=True)
        # Several sessions can start at once; one run is enough.
        with open(JHOME / ".pa-build.lock", "w") as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                return 0
            inst = Installer(args.quiet)
            inst.run()
    except BuildError as exc:
        print(f"ERROR {exc}", file=sys.stderr)
        return 1
    inst.info(f"installed into {JHOME} ({len(inst.changed)} changed, {len(inst.builder.warnings)} warnings)")
    for c in inst.changed:
        inst.info(f"  {c}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
